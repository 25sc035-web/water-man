/**
 * water-model.js
 * Water Model & Mass Balance Evaluation Engine for Textile Mills
 *
 * Implements evaluate(processes, factory, options)
 * Resolves water demand, recycling options, discharge limits, stage blends, and savings.
 */

function evaluate(processes, factory, options = {}) {
  // 1. Resolve inputs
  const procList = Array.isArray(processes) ? processes : [];
  const fact = factory || {};
  
  const freshWater = {
    tds: Number(fact.freshTds) || 150,
    hardness: Number(fact.freshHardness) || 80
  };
  
  const treatedWater = {
    tds: Number(fact.treatedTds) || 650,
    hardness: Number(fact.treatedHardness) || 200,
    availableVolume: Number(fact.treatedAvailable !== undefined ? fact.treatedAvailable : 7450)
  };

  const dischargeLimit = Number(fact.dischargeLimit !== undefined ? fact.dischargeLimit : 1450);
  const waterCost = Number(fact.waterCost) || 50;
  const workingDays = Number(fact.workingDays) || 26;
  const capacity = Number(fact.capacity) || 1000;
  const scenario = options.scenario || 'standard';

  // 2. Total Demand
  const totalDemand = procList.reduce((acc, p) => acc + (Number(p.water) || 0), 0);

  // 3. Delegate stage-level blend allocation to BlendOptimizer if available
  let blendResults = null;
  if (typeof BlendOptimizer !== 'undefined' && BlendOptimizer.allocateTreatedWater) {
    blendResults = BlendOptimizer.allocateTreatedWater({
      freshWater,
      treatedWater,
      stages: procList
    });
  }

  // Calculate base recycled and fresh volumes
  let totalRecycled = blendResults ? blendResults.totalRecycled : Math.min(treatedWater.availableVolume, totalDemand * 0.186);
  
  // Apply Scenario Multipliers if specified
  if (scenario === 'advanced') {
    // Advanced counter-current upgrades allow reclaiming +35% more water where quality permits
    totalRecycled = Math.min(totalDemand * 0.28, Math.round(totalRecycled * 1.35));
  } else if (scenario === 'eco_max') {
    // Closed-loop membrane ZLD reclamation
    totalRecycled = Math.min(totalDemand * 0.40, Math.round(totalRecycled * 1.72));
  }

  const totalFresh = Math.max(0, totalDemand - totalRecycled);
  const savingPercent = totalDemand > 0 ? Number(((totalRecycled / totalDemand) * 100).toFixed(1)) : 0;

  // 4. Closed-Loop Effluent Mass Balance
  // Raw wastewater generated by wet processes (typically ~62.75% of baseline demand)
  const rawWastewaterGenerated = Math.round(totalDemand * 0.6275);
  const etpInflow = rawWastewaterGenerated;
  const etpReusedToFactory = totalRecycled;
  
  // Final compliant discharge respecting regulatory discharge limit
  let finalDischarge = dischargeLimit;
  if (scenario === 'eco_max') {
    finalDischarge = 0; // Zero Liquid Discharge
  } else {
    finalDischarge = Math.min(dischargeLimit, Math.max(0, etpInflow - etpReusedToFactory));
  }

  // Sludge dewatering, membrane brine, and evaporative losses
  const etpSludgeAndEvap = Math.max(0, etpInflow - etpReusedToFactory - finalDischarge);

  // 5. Financial Cost Savings
  const dailyCostSaving = Math.round(totalRecycled * (waterCost / 1000));
  const monthlyCostSaving = Math.round(dailyCostSaving * workingDays);
  const annualCostSaving = Math.round(monthlyCostSaving * 12);

  // 6. Specific Water Consumption (L/kg fabric)
  const specificWaterBefore = capacity > 0 ? Number((totalDemand / capacity).toFixed(1)) : 0;
  const specificWaterAfter = capacity > 0 ? Number((totalFresh / capacity).toFixed(1)) : 0;

  return {
    totalDemand,
    totalFresh,
    totalRecycled,
    savingPercent,
    rawWastewaterGenerated,
    dischargeLimit,
    finalDischarge,
    etpSludgeAndEvap,
    dailyCostSaving,
    monthlyCostSaving,
    annualCostSaving,
    specificWaterBefore,
    specificWaterAfter,
    blendResults,
    perStage: blendResults ? blendResults.perStage : [],
    unusedTreatedWater: blendResults ? blendResults.unusedTreatedWater : 0
  };
}

// Expose evaluate globally on window and module
if (typeof window !== 'undefined') {
  window.evaluate = evaluate;
}
if (typeof module !== 'undefined' && module.exports) {
  module.exports = { evaluate };
}
